package com.mygame.arkanoid.objects.powerups;

/**
 * Liệt kê các loại vật phẩm tăng sức mạnh (Power-Up) trong trò chơi.
 */
public enum PowerUpType {
    EXPAND, // Mở rộng thanh đỡ
    EXTRA_LIFE, // Thêm mạng sống
    FAST_BALL, // Tăng tốc bóng
    MULTI_BALL, // Tạo nhiều bóng
    SLOW_BALL, // Giảm tốc bóng
    STICKY // Bóng dính vào thanh đỡ
}
